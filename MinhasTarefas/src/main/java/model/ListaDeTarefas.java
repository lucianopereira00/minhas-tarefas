package model;

public class ListaDeTarefas {
    private String tarefasDaFaculdade;
    private String tarefasDiarias;

    public String getTarefasDaFaculdade() {
        return tarefasDaFaculdade;
    }

    public void setTarefasDaFaculdade(String tarefasDaFaculdade) {
        this.tarefasDaFaculdade = tarefasDaFaculdade;
    }

    public String getTarefasDiarias() {
        return tarefasDiarias;
    }

    public void setTarefasDiarias(String tarefasDiarias) {
        this.tarefasDiarias = tarefasDiarias;
    }
}
